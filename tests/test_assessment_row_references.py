"""Regress the observed table-coordinate/passage-ID ambiguity and uncited comparison."""
import json
from pathlib import Path
import re
from types import SimpleNamespace
from unittest.mock import Mock

import pytest

from knowledgebase.providers.llm import LLMClient
from knowledgebase.rag.context import build_context
from knowledgebase.rag.generation import generate_answer, stream_answer
from knowledgebase.rag.sufficiency import assessment_context, assessment_excerpts
from knowledgebase.schemas import RetrievedChunk, Chunk

LIVE = Path(__file__).resolve().parents[1] / 'evals/library-runs/20260929-pdf-heading-acceptance'
CASES = [c['id'] for c in json.loads((LIVE/'frozen-cases.json').read_text())['cases']]


@pytest.fixture(scope='module')
def frozen_cases():
    cases = {}
    for name in CASES:
        raw = json.loads((LIVE/(name+'-planned.json')).read_text())
        chunks = [RetrievedChunk(file_name=s['file_name'], distance=s['distance'], pdf=s['pdf'],
            document_labels=s['document_labels'], chunk=Chunk.model_validate({**s, 'index': i}))
            for i, s in enumerate(raw['answer']['sources'])]
        cases[name] = raw, SimpleNamespace(evidence=SimpleNamespace(chunks=chunks))
    return cases


@pytest.mark.parametrize('name', CASES)
def test_frozen_sources_catalog_and_answer_context_are_unchanged(frozen_cases, name):
    raw, result = frozen_cases[name]
    original = [hit.model_dump() for hit in result.evidence.chunks]
    catalog = assessment_excerpts(result)
    assert catalog == raw['answer']['retrieval']['planning']['assessment']['evidence_catalog']
    context = assessment_context(result, catalog)
    assert re.sub(r'(?m)^(?:\[p\d+\])+ ', '', context) == build_context(result.evidence.chunks)
    assert build_context(result.evidence.chunks) == raw['answer']['retrieval']['planning']['assessment']['context']
    assert [hit.model_dump() for hit in result.evidence.chunks] == original
    # The marker is derived from the displayed row's canonical source span, not its coordinate.
    for hit in result.evidence.chunks:
        for table in hit.pdf.tables:
            for line in table.reading.splitlines():
                start, end = map(int, re.search(r'\(canonical offsets (\d+):(\d+)\):', line).groups())
                passages = [e for e in catalog if e['file_id'] == hit.chunk.file_id
                            and e['start_offset'] < end and start < e['end_offset']]
                assert passages
                assert ''.join(f"[{e['evidence_id']}]" for e in passages) + ' ' + line in context


@pytest.mark.parametrize(('label', 'coordinate', 'expected_id', 'incorrect_quote'), [
    ('Cash generated by operating activities', '15:16', 'p19', 'Inventories'),
    ('Cash used in financing activities', '31:32', 'p35', 'Proceeds from issuance of term debt'),
])
def test_cash_flow_reading_prints_actual_passage_id_beside_observed_confusing_row(
    frozen_cases, label, coordinate, expected_id, incorrect_quote,
):
    raw, result = frozen_cases['apple-cash-condition']
    catalog = assessment_excerpts(result)
    context = assessment_context(result, catalog)
    line = next(line for line in context.splitlines() if f'Row {coordinate} "{label}"' in line)
    assert line.startswith(f'[{expected_id}] Row {coordinate}')
    assert next(e['text'] for e in catalog if e['evidence_id'] == expected_id).startswith(label)
    misleading_id = 'p' + coordinate.split(':')[0]
    assert next(e['text'] for e in catalog if e['evidence_id'] == misleading_id).startswith(incorrect_quote)
    old_context = json.loads(next(m['content'] for m in raw['answer']['retrieval']['planning']['assessment']['record']['input']
                                 if m['role'] == 'user'))['context']
    assert f'\nRow {coordinate} "{label}"' in old_context


@pytest.mark.anyio
async def test_comparison_citation_guidance_reaches_both_paths_without_repairing_output(frozen_cases):
    raw, result = frozen_cases['apple-cash-condition']
    assessment = raw['answer']['retrieval']['planning']['assessment']
    llm = Mock(spec=LLMClient)
    llm.generate.return_value = raw['answer']['answer']
    answer = generate_answer(raw['request']['question'], result.evidence.chunks, llm, assessment=assessment)
    captured = []

    class Stream:
        async def stream(self, messages):
            captured.append(messages)
            for line in answer.splitlines(keepends=True):
                yield line

    parts = [p async for p in stream_answer(raw['request']['question'], result.evidence.chunks, Stream(), assessment=assessment)]
    messages = llm.generate.call_args.args[0]
    assert captured == [messages]
    assert messages[0]['content'].endswith('Sources:\n'+assessment['context'])
    assert 'Comparisons, arithmetic results and statements that a factual condition is met' in messages[1]['content']
    assert 'earlier operand bullets do not cover a later conclusion' in messages[1]['content']
    assert 'condition is met [1][2].' in messages[1]['content']
    assert ''.join(parts) == answer == raw['answer']['answer']
    conclusion = next(line for line in parts if 'comparison condition is met' in line)
    assert '[' not in conclusion  # Mocked replay must not manufacture a passing answer.

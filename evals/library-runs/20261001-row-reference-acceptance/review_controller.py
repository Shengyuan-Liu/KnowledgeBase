"""Retain the separate semantic review of both financial assessor selections."""
from datetime import datetime, timezone
from hashlib import sha256
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BASELINE = ROOT.parent / '20260929-pdf-heading-acceptance'

# Explicit reviewer mappings, based on the frozen original-page facts. Requirement
# IDs and order changed between samples, so compare their meanings, not positions.
ROLES = {
    'apple-securities': [
        ('current_securities', 'rq1', 'r1', 'p8', 'Marketable securities\t35,228\t31,590\n'),
        ('noncurrent_securities', 'rq2', 'r2', 'p15', 'Marketable securities\t91,479\t100,544\n'),
        ('balance_units', 'rq3', 'r3', 'p3', '(In millions, except number of shares, which are reflected in thousands, and par value)\n'),
    ],
    'apple-cash-condition': [
        ('cash_2024', 'req1', 'R1', 'p19', 'Cash generated by operating activities\t118,254\t110,543\n'),
        ('cash_2023', 'req2', 'R2', 'p19', 'Cash generated by operating activities\t118,254\t110,543\n'),
        ('cash_condition', 'req3', 'R5', 'p19', 'Cash generated by operating activities\t118,254\t110,543\n'),
        ('financing_2024', 'req4', 'R3', 'p35', 'Cash used in financing activities\t(121,983)\t(108,488)\n'),
        ('cash_units', 'req5', 'R4', 'p3', '(In millions)\n'),
    ],
}


def review_arm(root, arm):
    rows = []
    for case_id, roles in ROLES.items():
        path = root / (case_id + '-planned.json')
        raw = json.loads(path.read_text())
        assessment = raw['answer']['retrieval']['planning']['assessment']
        catalog = {p['evidence_id']: p for p in assessment['evidence_catalog']}
        requirements = {r['requirement_id']: r for r in assessment['requirements']}
        for role, before_id, after_id, expected_id, quote in roles:
            requirement = requirements[before_id if arm == 'before' else after_id]
            expected = catalog[expected_id]
            assert expected['text'] == quote
            # The same original-page groups, period headings and units are all in
            # supplied context. They are not necessarily model-selected references.
            if case_id == 'apple-securities':
                context_ids = ['p3', 'p4']
                if role == 'current_securities':
                    context_ids += ['p6']
                    assert catalog['p6']['text'] == 'Current assets:\n'
                elif role == 'noncurrent_securities':
                    context_ids += ['p14']
                    assert catalog['p14']['text'] == 'Non-current assets:\n'
                relevant_extras = {'p3', 'p4'}
                page = 2
            else:
                context_ids = ['p3', 'p4', 'p5']
                relevant_extras = set(context_ids)
                page = 3
            for identifier in context_ids:
                assert catalog[identifier]['text'] in assessment['context']
            assert expected['page_indices'] == [page - 1]
            references = requirement['references']
            selected = {r['evidence_id'] for r in references}
            for reference in references:
                actual = catalog[reference['evidence_id']]
                assert reference['quote'] == actual['text']
                assert reference['start_offset'] == actual['start_offset']
            irrelevant = sorted(selected - {expected_id} - relevant_extras)
            sufficient = expected_id in selected
            rows.append(dict(
                case_id=case_id, semantic_role=role,
                artifact=str(path.relative_to(ROOT.parent)),
                artifact_sha256=sha256(path.read_bytes()).hexdigest(),
                requirement_id=requirement['requirement_id'], description=requirement['description'],
                model_status=requirement['status'], model_selected_references=references,
                application_attached_table_context=requirement['table_context'],
                expected_supporting_passage=expected,
                supplied_disambiguating_context=[catalog[i] for i in context_ids],
                original_physical_page=page, requested_measure_has_selected_support=sufficient,
                irrelevant_selected_ids=irrelevant,
                supported_without_irrelevant_selections=sufficient and not irrelevant,
                reviewer_reason=(
                    'The selected row contains both operating-cash operands; 118254 > 110543. Periods and units are in supplied context.'
                    if role == 'cash_condition' and sufficient else
                    'Requested value/units are in the selected passage, with the correct period and row group in supplied context.'
                    if sufficient else
                    'Selected inventory or debt-issuance row does not support the requested operating/financing cash measure.'
                ) + (' Extra inventory selection does not contribute support.' if irrelevant and sufficient else ''),
            ))
    return dict(rows=rows, summary=dict(
        requirements=len(rows),
        with_required_selected_support=sum(r['requested_measure_has_selected_support'] for r in rows),
        supported_without_irrelevant_selections=sum(r['supported_without_irrelevant_selections'] for r in rows),
        requirements_with_irrelevant_selections=sum(bool(r['irrelevant_selected_ids']) for r in rows),
        selected_reference_instances=sum(len(r['model_selected_references']) for r in rows),
        irrelevant_reference_instances=sum(len(r['irrelevant_selected_ids']) for r in rows),
    ))


def main():
    before, after = review_arm(BASELINE, 'before'), review_arm(ROOT, 'after')
    record = dict(
        reviewed_at=datetime.now(timezone.utc).isoformat(), reviewer='Codex (model)', human_review=False,
        protocol='protocol.md#additional-assessor-selection-review',
        method='Read all eight financial requirements in each arm, selected exact source spans, attached headers, full supplied context and frozen original Apple pages 2 and 3. Semantic-role mappings are explicit reviewer decisions, not an automatic semantic judge.',
        independence='Separate from final-answer acceptance. Application-attached headers and full source context are not relabeled as model-selected evidence.',
        original_page_artifacts='../20260929-new-pdf-chain/source-review/',
        before=before, after=after,
        limitations=[
            'One sample of two familiar financial questions; no general reliability or causal guarantee.',
            'The cash-flow parser still combines beginning-balance text with date headings. Original-page review confirms column associations for these values; parsing was not changed.',
            'Periods, row groups and units need not all be explicitly selected; the frozen diagnostic allows disambiguation from actual supplied context.',
        ],
    )
    with (ROOT / 'controller-review.json').open('x') as output:
        output.write(json.dumps(record, indent=2) + '\n')
    print(json.dumps({arm: record[arm]['summary'] for arm in ['before', 'after']}, indent=2))


if __name__ == '__main__':
    main()

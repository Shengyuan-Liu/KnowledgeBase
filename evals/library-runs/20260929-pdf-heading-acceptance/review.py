"""Retain the model review of actual answers, source support and the citation miss."""
from datetime import datetime, timezone
from hashlib import sha256
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# These are explicit Codex review decisions after reading every answer and its
# supplied evidence, plus the retained original-page renders. No paid judge runs.
CLAIMS = {
    'paper-split': [
        ('Full-document split boundary', 'split at the full-document boundary', [1,2], [3,7], 1, 'only split on full-document boundaries'),
        ('Avoid shared-page evaluation advantage and style overfitting', 'overestimating prediction accuracy', [1,2], [3,7], 2, 'avoid overfitting on a particular style'),
    ],
    'paper-delivery': [
        ('PNG images', 'PNG format', [1], [3], 1, 'PNG'),
        ('1025 by 1025 pixels', '1025×1025 pixels', [1], [3], 1, '1025×1025 pixels'),
        ('Original PDF pages', 'original PDF pages', [1], [3], 1, 'provide the original PDF pages'),
        ('JSON sidecars with parsed text and coordinates', 'text-cell coordinates in JSON format', [1], [3], 1, 'sidecar files containing parsed PDF text and text-cell coordinates (in JSON)'),
    ],
    'lecture-bag-words': [
        ('Word order and position ignored', 'ignores the order of words and the position of words', [1], [60], 1, 'order of words on the page ignored'),
        ('Count documents per topic', 'number of documents from each topic', [4], [62], 4, 'Count how many documents you have from each topic (+ prior)'),
        ('Document counts estimate topic prior', 'used for estimating the prior P(Y)', [4], [62], 4, 'Prior P(Y)'),
        ('Count word occurrences within each topic', 'number of times each word appears in documents of that topic', [4], [62], 4, 'For each topic, count how many times you saw word in documents of this topic (+ prior)'),
        ('Word counts estimate topic-conditioned word likelihood', 'used for estimating P(X_i|Y)', [4], [62], 4, 'P(X i |Y)'),
    ],
    'lecture-midterm-date': [],
    'apple-securities': [
        ('Current securities are 35,228 million dollars at the requested date', '$35,228 million', [1], [2], 1, 'Marketable securities\t35,228\t31,590'),
        ('Non-current securities are 91,479 million dollars at the requested date', '$91,479 million', [1], [2], 1, 'Marketable securities\t91,479\t100,544'),
        ('Balance-sheet amounts in millions', 'units for both balances are in millions', [1], [2], 1, 'In millions'),
    ],
    'apple-cash-condition': [
        ('2024 operating cash is 118,254 million dollars', 'fiscal 2024: $118,254 million', [1], [3], 1, 'Cash generated by operating activities\t118,254\t110,543'),
        ('2023 operating cash is 110,543 million dollars', 'fiscal 2023: $110,543 million', [1], [3], 1, 'Cash generated by operating activities\t118,254\t110,543'),
        ('2024 exceeds 2023; condition met', 'the comparison condition is met.', [], [3], 1, 'Cash generated by operating activities\t118,254\t110,543'),
        ('2024 financing cash outflow is 121,983 million dollars', '$(121,983) million', [1], [3], 1, 'Cash used in financing activities\t(121,983)\t(108,488)'),
        ('Cash amounts in millions', 'units for all amounts are millions', [1], [3], 1, 'In millions'),
    ],
}
POINT_QUOTES = {
    'split_boundary':'full-document boundary', 'split_reason':'overestimating prediction accuracy',
    'page_images':'PNG format and have pixel dimensions of 1025×1025 pixels',
    'original_pages':'original PDF pages', 'sidecars':'text-cell coordinates in JSON format',
    'word_order':'ignores the order of words', 'topic_documents':'number of documents from each topic',
    'topic_words':'number of times each word appears in documents of that topic',
    'current_securities':'$35,228 million', 'noncurrent_securities':'$91,479 million',
    'balance_units':'units for both balances are in millions', 'cash_2024':'fiscal 2024: $118,254 million',
    'cash_2023':'fiscal 2023: $110,543 million', 'cash_condition':'the comparison condition is met.',
    'financing_2024':'$(121,983) million', 'cash_units':'units for all amounts are millions',
}


def main():
    frozen=json.loads((ROOT/'frozen-cases.json').read_text())
    rows=[]
    for case in frozen['cases']:
        path=ROOT/(case['id']+'-planned.json')
        raw=json.loads(path.read_text())
        answer=raw['answer']
        sources={s['source_id']:s for s in answer['sources']}
        claims=[]
        for claim, quote, citations, pages, support_id, support in CLAIMS[case['id']]:
            assert quote in answer['answer'] and support in sources[support_id]['text']
            assert set(pages) <= {r['page_index']+1 for i in (citations or [support_id]) for r in sources[i]['pdf']['regions']}
            sentence=next(line for line in answer['answer'].splitlines() if quote in line)
            assert all(f'[{i}]' in sentence for i in citations)
            if not citations:
                assert '[' not in sentence
            claims.append(dict(claim=claim, answer_quote=sentence, citation_ids=citations,
                supporting_source_ids=[support_id], original_physical_pages=pages,source_quote=support,
                correct=True,faithful=True,citation_supported=True if citations else None,
                citation_covered=bool(citations),page_metadata_correct=True,
                review_note='A separate factual comparison bullet lacks its own citation. Neighboring cited amounts support the inference but do not satisfy the per-item citation gate.' if not citations else 'Source text and original page support this claim.'))
        points=[]
        for fact in case['expected_fact_ids']:
            assert POINT_QUOTES[fact] in answer['answer']
            points.append(dict(fact_id=fact,correct=True,addressed=True,answer_quote=POINT_QUOTES[fact],
                reason='Matches frozen reference and actual supplied evidence. The question asks which counts; smoothing details are not a separate required point.' if fact in {'topic_documents','topic_words'} else 'Matches frozen reference and actual supplied evidence.'))
        history=all(raw[k] for k in ['history_matches','history_sources_shared_fields_match','history_sources_have_only_expected_schema_extra','history_retrieval_matches'])
        refusal=not case['answerable']
        plan=answer['retrieval']['planning']['trace']['plan']
        rows.append(dict(case_id=case['id'],artifact=path.name,artifact_sha256=sha256(path.read_bytes()).hexdigest(),
            answer=answer['answer'],expected_points=points,claims=claims,relevant=True,completed=raw['status']=='completed',
            history_matches=history,partial_refusal=False,full_refusal=refusal,appropriate_refusal=refusal,
            incorrect_refusal_on_answerable=False,refusal_review='Claim-free local refusal; exact calendar date remains absent under frozen reference review.' if refusal else None,
            passed=raw['status']=='completed' and history and all(c['citation_covered'] for c in claims),
            planner_classification=dict(route=plan['route'],dependencies=plan['dependencies'],answer_rules=plan['answer_rules'],
                requirements=plan['requirements'],note='Factual comparison and units are requirements; no factual condition in answer_rules. Unlike baseline, units are a requirement rather than an answer rule. Answer still states units.' if case['id']=='apple-cash-condition' else 'No unresolved-entity dependency required.')))
    all_claims=[c for r in rows for c in r['claims']]
    all_points=[p for r in rows for p in r['expected_points']]
    summary=dict(case_gate=dict(passed=sum(r['passed'] for r in rows),total=len(rows)),
        correctness=dict(correct=sum(p['correct'] for p in all_points),expected=len(all_points)),
        completeness=dict(addressed=sum(p['addressed'] for p in all_points),expected=len(all_points)),
        faithfulness=dict(supported=sum(c['faithful'] for c in all_claims),claims=len(all_claims)),
        relevance=dict(relevant=6,total=6),
        citation_support=dict(supported=sum(c['citation_supported'] is True for c in all_claims),cited_claims=sum(bool(c['citation_ids']) for c in all_claims)),
        citation_coverage=dict(supported_citations=sum(c['citation_covered'] for c in all_claims),citation_required_claims=len(all_claims)),
        abstention=dict(appropriate_unanswerable=1,unanswerable=1,incorrect_any_or_partial=0,answerable=5,incorrect_full=0),
        history_matches=sum(r['history_matches'] for r in rows))
    record=dict(reviewed_at=datetime.now(timezone.utc).isoformat(),reviewer='Codex (model)',human_review=False,
        method='Review every expected point and atomic factual claim against exact supplied context and original physical page renders using unchanged protocol. Correct arithmetic is separate from citation completeness.',
        original_page_review=['doclaynet pages 3 and 7','lecture pages 4, 60 and 62','Apple pages 2 and 3'],
        original_page_artifacts='../20260929-new-pdf-chain/source-review/',
        claim_inventory_note='Nineteen atomic claims: original answer scope plus two recovered count facts and two optional count-to-probability-label associations. These directly follow slide bullet labels; no formula derivation is tested.',
        cases=rows,summary=summary)
    with (ROOT/'review.json').open('x') as file:
        file.write(json.dumps(record,indent=2)+'\n')
    print(json.dumps(summary,indent=2))


if __name__=='__main__':
    main()

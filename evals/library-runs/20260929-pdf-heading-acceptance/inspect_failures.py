"""Retain citation and assessor-passage failures without repairing model outputs."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parent
BASELINE=ROOT.parent/'20260929-new-pdf-chain'


def load(case, root=ROOT):
    return json.loads((root/(case+'-planned.json')).read_text())


if __name__=='__main__':
    cash=load('apple-cash-condition')
    answer=cash['answer']
    assessment=answer['retrieval']['planning']['assessment']
    rows=[]
    for req in assessment['requirements']:
        if req['requirement_id']=='req5':
            continue
        expected='Cash used in financing activities' if req['requirement_id']=='req4' else 'Cash generated by operating activities'
        expected_passages=[p for p in assessment['evidence_catalog'] if expected in p['text']]
        assert expected_passages
        assert not any(expected in ref['quote'] for ref in req['references'])
        rows.append(dict(requirement_id=req['requirement_id'],description=req['description'],status=req['status'],
            chosen_references=req['references'],correct_available_passages=expected_passages,
            judgment='The chosen row does not support this requirement; correct row is available in the same supplied source.'))
    stocks=load('apple-securities')['answer']['retrieval']['planning']['assessment']
    stock_req=next(r for r in stocks['requirements'] if r['requirement_id']=='rq2')
    assert any('Inventories' in p['quote'] for p in stock_req['references'])
    assert any('91,479' in p['quote'] for p in stock_req['references'])
    missing=next(line for line in answer['answer'].splitlines() if 'comparison condition is met' in line)
    assert '[' not in missing
    observed=[json.loads(line) for line in (ROOT/'server-observations.jsonl').read_text().splitlines()]
    generation=next(o for o in observed if o['kind']=='sdk_start' and o['request']=='apple-cash-condition-planned' and o['input'].get('stream'))
    assert any('"source_ids": [1]' in item.get('content','') for item in generation['input']['input'])
    old=load('apple-cash-condition',BASELINE)['answer']['retrieval']['planning']['assessment']
    lecture=load('lecture-bag-words')['answer']['retrieval']['planning']['assessment']
    record=dict(reviewer='Codex (model)',human_review=False,
        citation_failure=dict(case_id='apple-cash-condition',exact_uncited_bullet=missing,
            factually_correct=True,faithful_to_supplied_context=True,required_inline_citation_present=False,
            source_number_available_to_generator=1,generation_observation_call_id=generation['call_id'],
            gate_effect='Fails the frozen per-item citation gate; no unsupported number or incorrect arithmetic.'),
        assessor_failures=dict(cash_requirements_without_supporting_selected_passage=rows,
            securities_extra_irrelevant_reference=stock_req,
            baseline_cash_requirements=[dict(description=r['description'],references=r['references']) for r in old['requirements']],
            gate_scope='Extra controller diagnostic, separate from the frozen final-answer gates. Valid IDs/exact quotes do not imply semantic relevance.',
            interpretation='Current generator receives the whole source and marks assessment as fallible guidance; final values are correct despite these wrong row selections. A single pass does not establish why IDs were misselected or that parent regrouping caused the citation omission.'),
        lecture_recovery=dict(round_index=lecture['round_index'],requirements=lecture['requirements'],
            conclusion='Both count requirements have exact page-62 support in round one; no supplementary retrieval is needed for this question.'),
        next_work='Investigate assessor row-ID selection and per-item citations for computed/comparison conclusions with frozen failure contexts; use offline regression before a bounded acceptance request. No automatic citation insertion or raw-evidence repair was performed.')
    with (ROOT/'failure-analysis.json').open('x') as file:
        file.write(json.dumps(record,indent=2)+'\n')
    print('Retained one uncited comparison, four incorrectly selected cash-flow requirement rows, and one extra irrelevant securities row. Lecture count support verified in round one.')

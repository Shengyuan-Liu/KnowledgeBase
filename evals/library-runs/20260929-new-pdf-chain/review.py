"""Retain Codex's source/claim review separately from numerical retrieval diagnostics."""
from datetime import datetime, timezone
from hashlib import sha256
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build_review():
    frozen = json.loads((ROOT / 'frozen-cases.json').read_text())
    rows = []
    # Claims are atomic review units, not one unit per generated bullet.
    claims = {
        'paper-split': [
            ('All pages from a document belong to one split.', [1, 2], [3, 7], 'only split on full-document boundaries'),
            ('This avoids an unfair evaluation advantage / overestimated accuracy from shared layouts.', [1, 2], [3, 7], 'overestimation of their prediction accuracy'),
        ],
        'paper-delivery': [
            ('Page image format is PNG.', [1], [3], 'PNG'),
            ('Image size is 1025 by 1025 pixels.', [1], [3], '1025×1025 pixels'),
            ('Original PDF pages are provided.', [1], [3], 'provide the original PDF pages'),
            ('JSON sidecars contain parsed text and text-cell coordinates.', [1], [3], 'sidecar files containing parsed PDF text and text-cell coordinates (in JSON)'),
        ],
        'lecture-bag-words': [
            ('Bag of words ignores word order.', [1], [60], 'order of words on the page ignored'),
        ],
        'lecture-midterm-date': [],
        'apple-securities': [
            ('Current marketable securities at September 28, 2024 are 35,228 million dollars.', [1], [2], 'Marketable securities\t35,228\t31,590'),
            ('Non-current marketable securities at September 28, 2024 are 91,479 million dollars.', [1], [2], 'Marketable securities\t91,479\t100,544'),
            ('Requested balance-sheet amounts are millions of dollars.', [1], [2], 'In millions'),
        ],
        'apple-cash-condition': [
            ('2024 operating cash is 118,254 million dollars.', [1], [3], 'Cash generated by operating activities\t118,254\t110,543'),
            ('2023 operating cash is 110,543 million dollars.', [1], [3], 'Cash generated by operating activities\t118,254\t110,543'),
            ('2024 operating cash exceeds 2023 operating cash.', [1], [3], 'Cash generated by operating activities\t118,254\t110,543'),
            ('2024 financing cash is an outflow of 121,983 million dollars.', [1], [3], 'Cash used in financing activities\t(121,983)\t(108,488)'),
            ('Requested cash-flow amounts are millions of dollars.', [1], [3], 'In millions'),
        ],
    }
    for case in frozen['cases']:
        path = ROOT / (case['id'] + '-planned.json')
        answer = json.loads(path.read_text())
        sources = {s['source_id']: s for s in answer['answer']['sources']}
        points = []
        for fact in case['expected_fact_ids']:
            correct = fact not in {'topic_documents', 'topic_words'}
            points.append(dict(fact_id=fact, correct=correct, addressed=correct,
                               reason='Matches the original page and supplied evidence.' if correct else
                               'Explicit partial refusal: indexed page 62 learning-count bullets were not supplied.'))
        reviewed_claims = []
        for text, citations, pages, quote in claims[case['id']]:
            assert quote in sources[citations[0]]['text']
            assert set(pages) <= {r['page_index'] + 1 for c in citations for r in sources[c]['pdf']['regions']}
            reviewed_claims.append(dict(claim=text, citation_ids=citations, original_physical_pages=pages,
                                       source_quote=quote, correct=True, faithful=True,
                                       citation_supported=True, citation_covered=True, page_metadata_correct=True))
        history = all(answer[k] for k in ['history_matches', 'history_sources_shared_fields_match',
                                         'history_sources_have_only_expected_schema_extra', 'history_retrieval_matches'])
        partial_refusal = case['id'] == 'lecture-bag-words'
        full_refusal = case['id'] == 'lecture-midterm-date'
        plan = answer['answer']['retrieval']['planning']['trace']['plan']
        rows.append(dict(case_id=case['id'], artifact=path.name, artifact_sha256=sha256(path.read_bytes()).hexdigest(),
                         answer=answer['answer']['answer'], expected_points=points, claims=reviewed_claims,
                         relevant=True, completed=answer['status'] == 'completed', history_matches=history,
                         partial_refusal=partial_refusal, full_refusal=full_refusal,
                         appropriate_refusal=full_refusal, incorrect_refusal_on_answerable=partial_refusal,
                         refusal_review=('Claim-free local refusal is appropriate; the exact date is absent.' if full_refusal else
                                         'The missing-information statement accurately describes the supplied context, but is a retrieval failure against the available source. It is an evidence-limit statement, not an externally factual claim needing a citation.' if partial_refusal else None),
                         passed=not partial_refusal,
                         planner_classification=dict(route=plan['route'], dependencies=plan['dependencies'], answer_rules=plan['answer_rules'],
                             note='The cash-flow factual condition remains a requirement and is absent from answer_rules; State the units. is retained as an answer rule.' if case['id']=='apple-cash-condition' else 'No unresolved-entity dependency in this case.')))
    record = dict(reviewed_at=datetime.now(timezone.utc).isoformat(), reviewer='Codex (model)', human_review=False,
                  method='Every emitted substantive factual claim checked against supplied source text and original rendered physical pages; every frozen expected point reviewed independently.',
                  scope='New development questions; no statistical generalization or comparison with the prior fixed-context run.',
                  post_answer_page_review=dict(file='source-review/doclaynet-page-7-post-answer.png',
                      reason='The answer also cited page 7, whose prose independently supports the page-3 split reference. Frozen labels were not broadened after answers.'),
                  cases=rows,
                  summary=dict(case_gate=dict(passed=5, total=6), correctness=dict(correct=14, expected=16),
                               completeness=dict(addressed=14, expected=16), faithfulness=dict(supported=15, claims=15),
                               relevance=dict(relevant=6, total=6), citation_support=dict(supported=15, cited_claims=15),
                               citation_coverage=dict(supported_citations=15, citation_required_claims=15),
                               abstention=dict(appropriate_unanswerable=1, unanswerable=1,
                                               incorrect_any_or_partial=1, answerable=5, incorrect_full=0),
                               history_matches=6))
    with (ROOT / 'review.json').open('x') as file:
        file.write(json.dumps(record, indent=2) + '\n')
    print('Reviewed 16 expected points and 15 emitted factual claims; 5/6 case gates pass. Lecture partial refusal remains a failure.')


if __name__ == '__main__':
    build_review()
